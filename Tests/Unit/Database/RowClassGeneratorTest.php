<?php

declare(strict_types=1);

namespace Tests\Unit\Database;

use Codeception\Test\Unit;
use Database\RowClassGenerator;

/**
 * Hermetic unit tests for Database\RowClassGenerator, which writes the source
 * of the row classes and enums from information_schema column metadata.
 */
final class RowClassGeneratorTest extends Unit
{
    private string $tsv = '';

    protected function _after(): void
    {
        if ($this->tsv !== '' && is_file($this->tsv)) {
            unlink($this->tsv);
        }
        $this->tsv = '';
    }

    public function testReadColumnsReadsTheDumpInOrder(): void
    {
        $columns = RowClassGenerator::readColumns($this->dump([
            "TABLE_NAME\tCOLUMN_NAME\tDATA_TYPE\tCOLUMN_TYPE\tIS_NULLABLE",
            "widgets\twidget_id\tINT\tint unsigned\tNO",
            "widgets\tnote\ttext\ttext\tYES",
        ]));

        $this->assertSame([
            ['table' => 'widgets', 'column' => 'widget_id', 'dataType' => 'int', 'columnType' => 'int unsigned', 'nullable' => false],
            ['table' => 'widgets', 'column' => 'note', 'dataType' => 'text', 'columnType' => 'text', 'nullable' => true],
        ], $columns);
    }

    public function testReadColumnsRefusesALineWithTheWrongNumberOfFields(): void
    {
        $this->expectException(\RuntimeException::class);
        $this->expectExceptionMessage('Malformed line: widgets	widget_id');

        RowClassGenerator::readColumns($this->dump([
            "TABLE_NAME\tCOLUMN_NAME\tDATA_TYPE\tCOLUMN_TYPE\tIS_NULLABLE",
            "widgets\twidget_id",
        ]));
    }

    public function testRenderTableWritesOneRowClassNamedAfterTheSingularTable(): void
    {
        $files = RowClassGenerator::renderTable('widget_statuses', [
            $this->column('widget_status_id', 'int', 'int unsigned'),
            $this->column('is_open', 'tinyint', 'tinyint(1)'),
            $this->column('label', 'varchar', 'varchar(40)', nullable: true),
            $this->column('made_at_utc', 'datetime', 'datetime(6)'),
        ]);

        $this->assertSame(['classes/Database/Row/WidgetStatusRow.php'], array_keys($files));
        $source = $files['classes/Database/Row/WidgetStatusRow.php'];

        $this->assertStringStartsWith(
            "<?php\n\ndeclare(strict_types=1);\n\n// Generated by tools/generate-row-classes.php from information_schema.\n",
            $source,
        );
        $this->assertStringContainsString("final readonly class WidgetStatusRow implements \\JsonSerializable\n", $source);
        $this->assertStringContainsString("        public int \$widgetStatusId,\n", $source);
        $this->assertStringContainsString("        public bool \$isOpen,\n", $source);
        $this->assertStringContainsString("        public ?string \$label,\n", $source);
        $this->assertStringContainsString("            label: RowValue::stringOrNull(\$row, 'label'),\n", $source);
        $this->assertStringContainsString("            'is_open' => (int) \$this->isOpen,\n", $source);
        $this->assertStringContainsString(
            "     * @return array{widget_status_id: int, is_open: 0|1, label: string|null, made_at_utc: string}\n",
            $source,
        );
    }

    public function testAnEnumColumnGetsItsOwnEnumFile(): void
    {
        $files = RowClassGenerator::renderTable('widgets', [
            $this->column('size', 'enum', "enum('small','extra-large','it''s big')"),
        ]);

        $this->assertSame(
            ['classes/Database/Enum/WidgetSize.php', 'classes/Database/Row/WidgetRow.php'],
            array_keys($files),
        );
        $this->assertStringContainsString(
            "enum WidgetSize: string\n{\n"
            . "    case Small = 'small';\n"
            . "    case ExtraLarge = 'extra-large';\n"
            . "    case ItSBig = 'it\\'s big';\n}\n",
            $files['classes/Database/Enum/WidgetSize.php'],
        );
        $this->assertStringContainsString(
            "        public \\Database\\Enum\\WidgetSize \$size,\n",
            $files['classes/Database/Row/WidgetRow.php'],
        );
    }

    public function testAColumnTypeWithNoMappingStopsTheRun(): void
    {
        $this->expectException(\RuntimeException::class);
        $this->expectExceptionMessage('No mapping yet for widgets.weight (nullable decimal(8,2)); add one to mapColumn()');

        RowClassGenerator::renderTable('widgets', [
            $this->column('weight', 'decimal', 'decimal(8,2)', nullable: true),
        ]);
    }

    /**
     * @return array{table: string, column: string, dataType: string, columnType: string, nullable: bool}
     */
    private function column(string $column, string $dataType, string $columnType, bool $nullable = false): array
    {
        return [
            'table' => 'widgets',
            'column' => $column,
            'dataType' => $dataType,
            'columnType' => $columnType,
            'nullable' => $nullable,
        ];
    }

    /**
     * @param list<string> $lines
     */
    private function dump(array $lines): string
    {
        $this->tsv = (string) tempnam(sys_get_temp_dir(), 'columns');
        file_put_contents($this->tsv, implode("\n", $lines) . "\n");

        return $this->tsv;
    }
}
